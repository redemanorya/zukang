unsigned char ACM86xx_Write_REG_WF( uint16 data_length, const  REG_TAB *reg_access_ptr )
{
    int i;

    for(i = 0; i < data_length; i++) 
    {
		 if(I2cWriteNByte(AMP_I2cHandler, ACM86xx_IIC_ADDR_WF, reg_access_ptr[i].Address, &reg_access_ptr[i].Data, 1) == FALSE)
			 {
			 	 APP_DBG("ACM8625_Write_REG Failed!");
				 return FALSE;
			 }

    }
    return 1;
}

unsigned char ACM86xx_Read_Reg_WF(uint8 RegAddr, uint8 *pData, uint8 len)
{
    if (AMP_I2cHandler != NULL)
    {
        return I2cReadNByte(AMP_I2cHandler, ACM86xx_IIC_ADDR_WF, RegAddr, pData, len);
    }
    else
    {
        return FALSE;
    }
}

