void LineInPlayResFree(void)
{
	AudioCoreSourceDisable(LINEIN_SOURCE_NUM);
#if (CFG_LINEIN_INPUT_SOURCE == LINEIN_INPUT_GC1808_I2S2)
	AudioI2S_RXDeInit(I2S2_MODULE);
#else
	AudioLineChannelSet(ANA_INPUT_CH_NONE);

	//AudioADC_Disable(LINEIN_ADC_SEL);
	AudioADC_DeInit(LINEIN_ADC_SEL);
#endif

	if(sLineInPlayCt->HwCt.ADCFifo != NULL)
	{
		APP_DBG("ADCFIFO\n");
		osPortFree(sLineInPlayCt->HwCt.ADCFifo);
		sLineInPlayCt->HwCt.ADCFifo = NULL;
	}
	AudioCoreSourceDeinit(LINEIN_SOURCE_NUM);
	
	osPortFree(sLineInPlayCt);
	sLineInPlayCt = NULL;
	APP_DBG("Line:Kill Ct\n");
}

bool LineInPlayResMalloc(uint16_t SampleLen)
{
#ifdef AUDIO_STREAM_UNINTERRUPT
	sLineInPlayCt = (LineInPlayContext*)osPortMallocFromEnd(sizeof(LineInPlayContext));
#else
	sLineInPlayCt = (LineInPlayContext*)osPortMalloc(sizeof(LineInPlayContext));
#endif
	if(sLineInPlayCt == NULL)
	{
		return FALSE;
	}
	memset(sLineInPlayCt, 0, sizeof(LineInPlayContext));

//	sLineInPlayCt->ADCFIFO_len =
	sLineInPlayCt->HwCt.ADCFifoLen = SampleLen * sizeof(PCM_DATA_TYPE) * 2 * 3;
	//LineIn5  digital (DMA)
#ifdef AUDIO_STREAM_UNINTERRUPT
	sLineInPlayCt->HwCt.ADCFifo = (uint32_t*)osPortMallocFromEnd(sLineInPlayCt->HwCt.ADCFifoLen);
#else
	sLineInPlayCt->HwCt.ADCFifo = (uint32_t*)osPortMalloc(sLineInPlayCt->HwCt.ADCFifoLen);
#endif
	if(sLineInPlayCt->HwCt.ADCFifo == NULL)
	{
		return FALSE;
	}
	memset(sLineInPlayCt->HwCt.ADCFifo, 0, sLineInPlayCt->HwCt.ADCFifoLen);

	return TRUE;
}

