#endif

// -----------------------------------------------------------------------------------------
// 计算DEVICE模式下EP1~EP5的总FIFO大小
#define DEVICE_HS_EP1_EP5_TOTAL ( \
    DEVICE_HS_EP1_TX_DEPTH + DEVICE_HS_EP1_RX_DEPTH + \
    DEVICE_HS_EP2_TX_DEPTH + DEVICE_HS_EP2_RX_DEPTH + \
    DEVICE_HS_EP3_TX_DEPTH + DEVICE_HS_EP3_RX_DEPTH + \
    DEVICE_HS_EP4_TX_DEPTH + DEVICE_HS_EP4_RX_DEPTH + \
    DEVICE_HS_EP5_TX_DEPTH + DEVICE_HS_EP5_RX_DEPTH  \
)

// 计算HOST模式下EP1~EP5的总FIFO大小
#define HOST_HS_EP1_EP5_TOTAL ( \
    HOST_HS_EP1_TX_DEPTH + HOST_HS_EP1_RX_DEPTH + \
    HOST_HS_EP2_TX_DEPTH + HOST_HS_EP2_RX_DEPTH + \
    HOST_HS_EP3_TX_DEPTH + HOST_HS_EP3_RX_DEPTH + \
    HOST_HS_EP4_TX_DEPTH + HOST_HS_EP4_RX_DEPTH + \
    HOST_HS_EP5_TX_DEPTH + HOST_HS_EP5_RX_DEPTH  \
)

// 分别检查两种模式下总大小是否超过8KB（8192字节），超过则编译报错
#if DEVICE_HS_EP1_EP5_TOTAL > 8192
#error "DEVICE mode: EP1~EP5 total FIFO size exceeds 8KB!"
#endif

#if HOST_HS_EP1_EP5_TOTAL > 8192
#error "HOST mode: EP1~EP5 total FIFO size exceeds 8KB!"
#endif

extern uint16_t  OTG_HS_EP_FIFO_CONFIG[];


void OTG_HS_HostFifoInit(void)
{
    uint16_t index = 0;

    OTG_HS_EP_FIFO_CONFIG[index++] = 64;
    OTG_HS_EP_FIFO_CONFIG[index++] = 64;

    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP1_TX_DEPTH;
    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP1_RX_DEPTH;

    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP2_TX_DEPTH;
    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP2_RX_DEPTH;

    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP3_TX_DEPTH;
    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP3_RX_DEPTH;

    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP4_TX_DEPTH;
    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP4_RX_DEPTH;

    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP5_TX_DEPTH;
    OTG_HS_EP_FIFO_CONFIG[index++] = HOST_HS_EP5_RX_DEPTH;
}


