int8_t ACM8625_Write_REG(uint16_t data_length,   const        REG_TAB *reg_access_ptr)
{
    int i;

    for(i = 0; i < data_length; i++)
    {
			 if(I2cWriteNByte(AMP_I2cHandler, I2C_ADD_ACM8625, reg_access_ptr[i].Address, &reg_access_ptr[i].Data, 1) == FALSE)
			 {
			 	 APP_DBG("ACM8625_Write_REG Failed!");
				 return FALSE;
			 }
			 
			 if(I2cWriteNByte(AMP_I2cHandler, I2C_ADD_ACM8625pro, reg_access_ptr[i].Address, &reg_access_ptr[i].Data, 1) == FALSE)
			 {
			 	 APP_DBG("ACM8625_Write_REG Failed!");
				 return FALSE;
			 }
    }
    return TRUE;
}
void ACM8625_Write_REG1(uint16_t data_length,   const        REG_TAB *reg_access_ptr)
{
    int i;

    for(i = 0; i < data_length; i++)
    {
		I2cWriteNByte(AMP_I2cHandler, I2C_ADD_ACM8625, reg_access_ptr[i].Address, &reg_access_ptr[i].Data, 1);
		
		I2cWriteNByte(AMP_I2cHandler, I2C_ADD_ACM8625pro, reg_access_ptr[i].Address, &reg_access_ptr[i].Data, 1);
    }

}
